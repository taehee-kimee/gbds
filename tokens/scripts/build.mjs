#!/usr/bin/env node
// Builds dist/ from the DTCG sources in src/. No dependencies.
//
//   src/primitives.json      tier 1, mode-less
//   src/effects.json         shadows, rings, blur
//   src/typography.json      size + line-height composites
//   src/semantic.light.json  tier 2, Light mode
//   src/semantic.dark.json   tier 2, Dark mode — must have exactly the same keys
//
// CSS name = "--gs-" + token path joined with "-": background.surface-secondary → --gs-background-surface-secondary.
// References ({color.neutral.50}) are emitted as var(--gs-…) so the alias chain survives in the browser.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs"

const SRC = new URL("../src/", import.meta.url)
const DIST = new URL("../dist/", import.meta.url)
const read = (file) => JSON.parse(readFileSync(new URL(file, SRC), "utf8"))

function flatten(tree, path = [], inheritedType) {
  const type = tree.$type ?? inheritedType
  const out = []
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith("$")) continue
    const p = [...path, key]
    if ("$value" in node) {
      out.push({ path: p, type: node.$type ?? type, value: node.$value })
    } else {
      out.push(...flatten(node, p, type))
    }
  }
  return out
}

const constant = [
  ...flatten(read("primitives.json")),
  ...flatten(read("effects.json")),
  ...flatten(read("typography.json")),
]
const light = flatten(read("semantic.light.json"))
const dark = flatten(read("semantic.dark.json"))

// --- validation --------------------------------------------------------------

const errors = []
const PREFIX = "gs"
const cssName = (path) => `--${PREFIX}-${path.join("-")}`

const known = new Set([...constant, ...light].map((t) => t.path.join(".")))
const owner = new Map()
for (const t of [...constant, ...light]) {
  const name = cssName(t.path)
  const prev = owner.get(name)
  if (prev && prev !== t.path.join(".")) errors.push(`${name} is produced by both ${prev} and ${t.path.join(".")}`)
  owner.set(name, t.path.join("."))
}

const lightKeys = light.map((t) => t.path.join(".")).sort()
const darkKeys = dark.map((t) => t.path.join(".")).sort()
for (const k of lightKeys) if (!darkKeys.includes(k)) errors.push(`dark mode is missing ${k}`)
for (const k of darkKeys) if (!lightKeys.includes(k)) errors.push(`light mode is missing ${k}`)

const REF = /\{([\w.-]+)\}/g
function checkRefs(t) {
  for (const [, ref] of JSON.stringify(t.value).matchAll(REF)) {
    if (!known.has(ref)) errors.push(`${t.path.join(".")} references unknown token {${ref}}`)
  }
}
;[...constant, ...light, ...dark].forEach(checkRefs)

if (errors.length) {
  console.error(`Token build failed:\n  ${errors.join("\n  ")}`)
  process.exit(1)
}

// --- CSS ---------------------------------------------------------------------

const ref = (value) => String(value).replace(REF, (_, p) => `var(${cssName(p.split("."))})`)
const quoteFamily = (f) => (/\s/.test(f) ? `"${f}"` : f)

function cssValue({ type, value }) {
  switch (type) {
    case "fontFamily":
      return Array.isArray(value) ? value.map(quoteFamily).join(", ") : ref(value)
    case "shadow":
      return [value]
        .flat()
        .map((s) => `${s.inset ? "inset " : ""}${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${ref(s.color)}`)
        .join(", ")
    case "typography":
      // `font` shorthand: weight size/line-height family
      return ref(`${value.fontWeight} ${value.fontSize}/${value.lineHeight} ${value.fontFamily}`)
    default:
      return ref(value)
  }
}

const declarations = (tokens) => tokens.map((t) => `  ${cssName(t.path)}: ${cssValue(t)};`).join("\n")

const header = "/* Generated by tokens/scripts/build.mjs from tokens/src/*.json — do not edit by hand. */"
const css = `${header}

:root {
${declarations(constant)}
}

:root,
[data-theme="light"] {
  color-scheme: light;
${declarations(light)}
}

[data-theme="dark"] {
  color-scheme: dark;
${declarations(dark)}
}
`

mkdirSync(DIST, { recursive: true })
writeFileSync(new URL("tokens.css", DIST), css)

console.log(`tokens: ${constant.length} constant + ${light.length} semantic (light/dark) → dist/`)
